package com.talentflow.backend.entity;

import jakarta.persistence.*;
import java.util.Objects;

@Entity
@Table(name = "skills", indexes = {
        @Index(name = "idx_skills_name", columnList = "name", unique = true),
        @Index(name = "idx_skills_category", columnList = "category")
})
public class Skill {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, unique = true, length = 100)
    private String name;

    @Enumerated(EnumType.STRING)
    @Column(length = 50)
    private SkillCategory category = SkillCategory.GENERAL;

    public Skill() {}

    public Skill(String name, SkillCategory category) {
        this.name = name;
        this.category = category;
    }

    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }

    public String getName() { return name; }
    public void setName(String name) { this.name = name; }

    public SkillCategory getCategory() { return category; }
    public void setCategory(SkillCategory category) { this.category = category; }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (o == null || getClass() != o.getClass()) return false;
        Skill skill = (Skill) o;
        return Objects.equals(id, skill.id) && Objects.equals(name, skill.name);
    }

    @Override
    public int hashCode() {
        return Objects.hash(id, name);
    }
}

